import test from 'node:test';
import assert from 'node:assert/strict';
import {createHash,randomUUID} from 'node:crypto';
import {mkdtemp,mkdir,rm,readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {startRegistry} from '../src-server/registry.mjs';
const sha=value=>createHash('sha256').update(value).digest('hex');

test('published metadata survives restart and a priced version requires an entitlement for both artifact reads',async t=>{
  const data=await mkdtemp(path.join(os.tmpdir(),'registry-price-')),token=randomUUID();
  let server=await startRegistry({data,token});
  t.after(async()=>{await server.close();await rm(data,{recursive:true,force:true});});
  const bytes='team',headers={authorization:'Bearer '+token,'x-content-sha256':sha(bytes)};
  const route=()=>server.url+'/v1/resources/talent/team/1.2.0';
  const metadata={name:'Team',developer:'Publishing team',summary:'A review team',priceCnyFen:1250,logo:'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jWZkAAAAASUVORK5CYII='};
  assert.equal((await fetch(route()+'/draft',{method:'PUT',headers,body:bytes})).status,201);
  assert.equal((await fetch(route()+'/publish',{method:'POST',headers,body:JSON.stringify(metadata)})).status,200);
  await server.close();server=await startRegistry({data,token});
  assert.deepEqual((await (await fetch(server.url+'/v1/resources')).json())[0].metadata,metadata);
  assert.equal((await fetch(route()+'/lock')).status,403);
  assert.equal((await fetch(route()+'/download?sha256='+sha(bytes))).status,403);
  assert.equal((await fetch(route()+'/publish',{method:'POST',headers,body:'{"priceCnyFen":0}'})).status,409);
});

test('two independent clients: draft, publication, pinned recovery after upgrade and restart',async t=>{
  const root=await mkdtemp(path.join(os.tmpdir(),'cbim-registry-'));
  const data=path.join(root,'server'),a=path.join(root,'author'),b=path.join(root,'consumer');
  const token=randomUUID(); let server;
  t.after(async()=>{try{await server?.close();}finally{await rm(root,{recursive:true,force:true});}});
  await Promise.all([mkdir(a),mkdir(b)]);
  server=await startRegistry({data,token});
  const request=(v,action,options)=>fetch(server.url+'/v1/resources/talent/planner/'+v+'/'+action,options);
  const upload=async(v,content)=>{
    await writeFile(path.join(a,'template.json'),content);
    const body=await readFile(path.join(a,'template.json'));
    const headers={authorization:'Bearer '+token,'x-content-sha256':sha(body)};
    return {headers,response:await request(v,'draft',{method:'PUT',headers,body})};
  };
  const first='{"role":"planner","skills":[]}';
  assert.equal((await request('1.0.0','draft',{method:'PUT',body:first})).status,401);
  const {headers,response}=await upload('1.0.0',first);
  assert.equal(response.status,201);
  assert.equal((await upload('1.0.0',first)).response.status,200);
  assert.deepEqual(await (await fetch(server.url+'/v1/resources')).json(),[]);
  assert.equal((await request('1.0.0','lock')).status,404);
  assert.equal((await request('1.0.0','download?sha256='+sha(first))).status,404);
  assert.equal((await request('1.0.0','publish',{method:'POST',headers})).status,200);
  const lock=await (await request('1.0.0','lock')).json();
  await writeFile(path.join(b,'lock.json'),JSON.stringify(lock));
  const second='{"role":"planner","skills":["review"]}';
  const v2=await upload('2.0.0',second);
  assert.equal(v2.response.status,201);
  assert.equal((await request('2.0.0','publish',{method:'POST',headers:v2.headers})).status,200);
  assert.equal((await upload('1.0.0',second)).response.status,409);
  assert.equal((await request('3.0.0','draft',{method:'PUT',headers,body:second})).status,422);
  await server.close();server=undefined;
  server=await startRegistry({data,token});
  assert.equal((await (await fetch(server.url+'/v1/resources')).json()).length,2);
  const pinned=JSON.parse(await readFile(path.join(b,'lock.json'),'utf8'));
  assert.equal((await request('1.0.0','download?sha256='+sha(second))).status,409);
  const download=await fetch(server.url+pinned.download);
  assert.equal(download.status,200);
  const bytes=Buffer.from(await download.arrayBuffer());
  assert.equal(sha(bytes),pinned.sha256);
  await writeFile(path.join(b,'template.json'),bytes);
  assert.equal(await readFile(path.join(b,'template.json'),'utf8'),first);
  assert.equal(await readFile(path.join(a,'template.json'),'utf8'),second);
});
